package com.vyoog.report;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.FontFactory;
import com.lowagie.text.Image;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfTemplate;
import com.lowagie.text.pdf.PdfWriter;
import com.vyoog.release.ReadinessSnapshotService.Snapshot;
import com.vyoog.report.TrendService.Trends;
import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.time.ZoneOffset;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import org.apache.poi.ss.usermodel.CellStyle;
import org.apache.poi.ss.usermodel.FillPatternType;
import org.apache.poi.ss.usermodel.IndexedColors;
import org.apache.poi.ss.usermodel.Row;
import org.apache.poi.ss.usermodel.Sheet;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;

/**
 * VYB-0956 (F24, D43): the trend report as an Excel workbook and as a PDF. Both carry the same figures as the screen: a summary of
 * what was asked, then defects, pass rate and release readiness. Where there is nothing recorded the cell says so ("no results",
 * "no data"); it is never a zero. A PDF chart is drawn with plain rectangles and every bar is also in the table beside it, so
 * nothing depends on colour. The PDF uses the built-in Latin-1 font, so a character outside it is written as "?".
 */
final class TrendReportWriter {

    static final String NO_RESULTS = "no results";
    static final String NO_DATA = "no data";

    private TrendReportWriter() {}

    private static String scopeLine(Trends t) {
        if (t.applicationName() != null) return "Application: " + t.applicationName() + (t.productName() != null ? " (product " + t.productName() + ")" : "");
        if (t.productName() != null) return "Product: " + t.productName();
        return "All products";
    }

    static String percent(Double rate) { return rate == null ? NO_RESULTS : String.format(Locale.ROOT, "%.0f%%", rate * 100); }

    private static String verifiedShare(Snapshot s) {
        return s.committed() == 0 ? "no scope" : String.format(Locale.ROOT, "%.0f%%", 100.0 * s.verified() / s.committed());
    }

    // ------------------------------------------------------------------ Excel

    static byte[] xlsx(Trends t, String generatedBy) {
        try (XSSFWorkbook wb = new XSSFWorkbook(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            CellStyle head = wb.createCellStyle();
            var bold = wb.createFont();
            bold.setBold(true);
            head.setFont(bold);
            head.setFillForegroundColor(IndexedColors.GREY_25_PERCENT.getIndex());
            head.setFillPattern(FillPatternType.SOLID_FOREGROUND);

            Sheet summary = wb.createSheet("Summary");
            String[][] lines = {
                {"Vyoog trend report", ""},
                {"Generated", t.generatedAt().toString()},
                {"Generated by", generatedBy},
                {"Period", "last " + t.days() + " days, in weeks starting Monday (UTC)"},
                {"Scope", scopeLine(t)},
                {"Release", t.readiness() == null ? "none chosen" : t.readiness().releaseName() + " (" + t.readiness().state() + ")"},
                {"Notes", "Counts and rates only. A week with no test results has no rate. Readiness is recorded once a day from the day it was first recorded."},
            };
            for (int i = 0; i < lines.length; i++) {
                Row r = summary.createRow(i);
                r.createCell(0).setCellValue(lines[i][0]);
                r.createCell(1).setCellValue(lines[i][1]);
                if (i == 0) r.getCell(0).setCellStyle(head);
            }
            summary.setColumnWidth(0, 18 * 256);
            summary.setColumnWidth(1, 90 * 256);

            Sheet defects = sheet(wb, head, "Defects", "Week starting", "Raised", "Closed", "Open at end of week");
            int n = 1;
            for (var d : t.defects()) {
                Row r = defects.createRow(n++);
                r.createCell(0).setCellValue(d.weekStart().toString());
                r.createCell(1).setCellValue(d.opened());
                r.createCell(2).setCellValue(d.closed());
                r.createCell(3).setCellValue(d.open());
            }

            Sheet pass = sheet(wb, head, "Pass rate", "Week starting", "Passed", "Failed", "Pass rate");
            n = 1;
            for (var p : t.passRate()) {
                Row r = pass.createRow(n++);
                r.createCell(0).setCellValue(p.weekStart().toString());
                r.createCell(1).setCellValue(p.passed());
                r.createCell(2).setCellValue(p.failed());
                if (p.rate() == null) r.createCell(3).setCellValue(NO_RESULTS);
                else r.createCell(3).setCellValue(p.rate());
            }
            CellStyle pct = wb.createCellStyle();
            pct.setDataFormat(wb.createDataFormat().getFormat("0%"));
            for (int i = 1; i < n; i++) if (pass.getRow(i).getCell(3).getCellType() == org.apache.poi.ss.usermodel.CellType.NUMERIC) pass.getRow(i).getCell(3).setCellStyle(pct);

            Sheet ready = sheet(wb, head, "Readiness", "Day", "Committed", "Approved", "Verified", "Blocked", "Open critical gaps", "Verified share");
            if (t.readiness() == null) {
                ready.createRow(1).createCell(0).setCellValue("No release was chosen.");
            } else {
                n = 1;
                for (Snapshot s : t.readiness().history()) readinessRow(ready.createRow(n++), s.takenOn().toString(), s);
                readinessRow(ready.createRow(n), "Now (live, not recorded)", t.readiness().current());
                if (t.readiness().history().isEmpty()) ready.createRow(n + 1).createCell(0).setCellValue("No days recorded in this period yet.");
            }
            for (Sheet s : List.of(defects, pass, ready)) for (int c = 0; c < 7; c++) s.setColumnWidth(c, (c == 0 ? 26 : 20) * 256);

            wb.write(out);
            return out.toByteArray();
        } catch (IOException e) {
            throw new IllegalStateException("Could not write the workbook", e);
        }
    }

    private static Sheet sheet(XSSFWorkbook wb, CellStyle head, String name, String... headers) {
        Sheet s = wb.createSheet(name);
        Row r = s.createRow(0);
        for (int i = 0; i < headers.length; i++) {
            r.createCell(i).setCellValue(headers[i]);
            r.getCell(i).setCellStyle(head);
        }
        return s;
    }

    private static void readinessRow(Row r, String label, Snapshot s) {
        r.createCell(0).setCellValue(label);
        r.createCell(1).setCellValue(s.committed());
        r.createCell(2).setCellValue(s.approved());
        r.createCell(3).setCellValue(s.verified());
        r.createCell(4).setCellValue(s.blocked());
        r.createCell(5).setCellValue(s.criticalGaps());
        r.createCell(6).setCellValue(verifiedShare(s));
    }

    // ------------------------------------------------------------------ PDF

    private static final Font TITLE = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 18);
    private static final Font H2 = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 12);
    private static final Font BODY = FontFactory.getFont(FontFactory.HELVETICA, 9);
    private static final Font HEAD = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 9);
    private static final Font NOTE = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 8, Font.NORMAL, new Color(90, 90, 90));

    /** Latin-1 only: the built-in font has nothing else. */
    static String latin1(String s) {
        StringBuilder b = new StringBuilder();
        for (char c : s.toCharArray()) b.append(c <= 0xFF ? c : '?');
        return b.toString();
    }

    static byte[] pdf(Trends t, String generatedBy) {
        try (ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Document doc = new Document(PageSize.A4, 40, 40, 40, 40);
            PdfWriter writer = PdfWriter.getInstance(doc, out);
            doc.open();
            doc.add(new Paragraph("Vyoog trend report", TITLE));
            doc.add(new Paragraph(latin1(scopeLine(t) + "  |  last " + t.days() + " days, weeks starting Monday (UTC)"), BODY));
            doc.add(new Paragraph(latin1("Generated " + t.generatedAt().atOffset(ZoneOffset.UTC).toLocalDateTime().withNano(0) + " UTC by " + generatedBy), NOTE));
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Defects", H2));
            doc.add(new Paragraph("Raised and closed each week, and the backlog (open or fixed, not closed) at the end of it.", NOTE));
            doc.add(chart(writer, t.defects().stream().map(d -> (double) d.open()).toList(), null));
            PdfPTable defects = table(4, "Week starting", "Raised", "Closed", "Open at end");
            for (var d : t.defects()) addRow(defects, d.weekStart().toString(), String.valueOf(d.opened()), String.valueOf(d.closed()), String.valueOf(d.open()));
            doc.add(defects);
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Test pass rate", H2));
            doc.add(new Paragraph("Of the results recorded each week, the share that passed. A week with no results has no rate.", NOTE));
            doc.add(chart(writer, t.passRate().stream().map(p -> p.rate()).toList(), 1.0));
            PdfPTable pass = table(4, "Week starting", "Passed", "Failed", "Pass rate");
            for (var p : t.passRate()) addRow(pass, p.weekStart().toString(), String.valueOf(p.passed()), String.valueOf(p.failed()), percent(p.rate()));
            doc.add(pass);
            doc.add(new Paragraph(" "));

            doc.add(new Paragraph("Release readiness", H2));
            if (t.readiness() == null) {
                doc.add(new Paragraph("No release was chosen.", BODY));
            } else {
                doc.add(new Paragraph(latin1(t.readiness().releaseName() + " (" + t.readiness().state() + "). Recorded once a day; a day not listed has no data."), NOTE));
                doc.add(chart(writer, t.readiness().history().stream().map(s -> s.committed() == 0 ? null : (double) s.verified() / s.committed()).toList(), 1.0));
                PdfPTable ready = table(7, "Day", "Committed", "Approved", "Verified", "Blocked", "Crit. gaps", "Verified share");
                List<Snapshot> rows = new ArrayList<>(t.readiness().history());
                for (Snapshot s : rows) addRow(ready, s.takenOn().toString(), String.valueOf(s.committed()), String.valueOf(s.approved()), String.valueOf(s.verified()),
                    String.valueOf(s.blocked()), String.valueOf(s.criticalGaps()), verifiedShare(s));
                Snapshot now = t.readiness().current();
                addRow(ready, "Now (live)", String.valueOf(now.committed()), String.valueOf(now.approved()), String.valueOf(now.verified()),
                    String.valueOf(now.blocked()), String.valueOf(now.criticalGaps()), verifiedShare(now));
                doc.add(ready);
                if (rows.isEmpty()) doc.add(new Paragraph("No days recorded in this period yet.", NOTE));
            }
            doc.close();
            return out.toByteArray();
        } catch (DocumentException | IOException e) {
            throw new IllegalStateException("Could not write the PDF", e);
        }
    }

    private static PdfPTable table(int columns, String... headers) {
        PdfPTable table = new PdfPTable(columns);
        table.setWidthPercentage(100);
        table.setHeaderRows(1);
        for (String h : headers) {
            PdfPCell c = new PdfPCell(new Phrase(h, HEAD));
            c.setBackgroundColor(new Color(225, 225, 225));
            c.setPadding(3);
            table.addCell(c);
        }
        return table;
    }

    private static void addRow(PdfPTable table, String... values) {
        for (String v : values) {
            PdfPCell c = new PdfPCell(new Phrase(latin1(v), BODY));
            c.setPadding(3);
            table.addCell(c);
        }
    }

    /**
     * A bar chart as one image: a bar per value, a missing value drawn as a thin outline (nothing recorded), never as a zero bar.
     * {@code fixedMax} fixes the scale (a rate is out of 1); null scales to the largest value.
     */
    private static Image chart(PdfWriter writer, List<Double> values, Double fixedMax) throws DocumentException {
        float w = 515, h = 70;
        PdfTemplate t = writer.getDirectContent().createTemplate(w, h);
        double max = fixedMax != null ? fixedMax : Math.max(1, values.stream().filter(v -> v != null).mapToDouble(Double::doubleValue).max().orElse(1));
        t.setColorStroke(new Color(160, 160, 160));
        t.moveTo(0, 0.5f);
        t.lineTo(w, 0.5f);
        t.stroke();
        if (!values.isEmpty()) {
            float slot = w / values.size();
            float bar = Math.min(24f, slot * 0.6f);
            for (int i = 0; i < values.size(); i++) {
                float x = i * slot + (slot - bar) / 2;
                Double v = values.get(i);
                if (v == null) {
                    t.setColorStroke(new Color(160, 160, 160));
                    t.rectangle(x, 0.5f, bar, 6);
                    t.stroke();
                } else {
                    t.setColorFill(new Color(40, 90, 150));
                    t.rectangle(x, 0.5f, bar, (float) (v / max * (h - 6)));
                    t.fill();
                }
            }
        }
        Image img = Image.getInstance(t);
        img.setAlignment(Element.ALIGN_LEFT);
        return img;
    }
}
